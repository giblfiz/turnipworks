#!/usr/bin/env python3
"""REUSE (Harry 2026-11-07: "is there anything we can bring over or re-use from our existing model sets? Like fantasy surely
has some useful stuff"). The library's own fantasy / regional roles that a blind Gemini era read called present-day at table
distance (reuse-borrow.json `accepted`, by tools/reuse_read.py + reuse_decide.py) join the modern rooms that USE them:
  1. tools/spawn-tuner/js/solver2.js MX_BORROW (between the markers): role -> the vetted looks (skus) a modern room may roll
     (a pewter or wicker look of the same role never does)
  2. the role's own catalog line gets `MOD` in its `set:` (the catalog's multi-set membership: engine/tools/build_types.py
     puts a MOD role on the shelves of the Modern buildings whose rooms name it)
Only the roles named in USED (what this lane's room programs and recipes lay) are synced: the rest of the vetted list is
there for the next modern room. Idempotent. Run from the repo root:  python3 experiments/2026-11-07-modrooms/integration/borrow_sync.py"""
import json, re, sys
from pathlib import Path
R = Path.cwd(); E = R / 'experiments/2026-11-07-modrooms'
assert (R / 'tools/spawn-tuner/js/solver2.js').exists(), 'run from the repo root'
ACC = json.loads((E / 'reuse-borrow.json').read_text())['accepted']
USED = [  # kitchen: on the prep tables, crates by the shelving, racks on the wall
    'cabbage-single', 'carrot-pile', 'onion-pile', 'potato', 'bread-loaf', 'bread-long-loaf', 'cheese-wheel-cut', 'meat-raw-joint', 'garlic-bulb',
    'apple', 'sausage-link', 'egg', 'ham-sliced', 'saucepan-copper', 'roasting-pan', 'plate-ceramic', 'platter-board-handled',
    'vegetable-crate-mixed', 'potato-crate', 'apple-crate', 'fruit-crate-mixed', 'vegetable-basket-mixed', 'knife-rack-wall', 'utensil-rack-wall',
    # penthouse: rugs, plants, a bust, the coffee table's tray and flowers, a wine rack
    'rug-round-fine', 'rug-round', 'rug-oval', 'rug-grand', 'rug-striped-woven', 'rug-cowhide', 'rug-sheepskin',
    'fern-potted', 'palm-potted', 'citrus-tree-tub', 'planter-topiary', 'statue-bust', 'vase-flowers', 'tea-service-tray', 'wine-rack',
    # bathroom: towels, the bath mat, a pot plant; fire escape: pot plants; (and the fire escape's railing, read by hand: plain bars)
    'towel-hanging', 'towel-stack', 'rug-runner', 'plant-pot', 'herb-pot']
EXTRA = {'railing-iron': ['railing-iron']}  # (not on the Gemini sheets: a plain bar railing, the fire escape's)
missing = [r for r in USED if r not in ACC]
if missing: sys.exit(f'REFUSING: not in reuse-borrow.json accepted: {missing}')
borrow = {r: ACC[r]['skus'] for r in USED} | EXTRA
# 1. solver2.js MX_BORROW
p = R / 'tools/spawn-tuner/js/solver2.js'; s = p.read_text()
a, b = '// >>> mx:borrow\n', '// <<< mx:borrow\n'
body = ''.join(f"  {json.dumps(k)}: {json.dumps(v)},\n" for k, v in borrow.items())
block = f"{a}export const MX_BORROW = {{ // (generated by experiments/2026-11-07-modrooms/integration/borrow_sync.py from reuse-borrow.json: edit there)\n{body}}};\n{b}"
if a in s: s = s[:s.index(a)] + block + s[s.index(b) + len(b):]
else:
    m = re.search(r"export const MX_BORROW = \{.*?\n\};\n", s, re.S); assert m, 'MX_BORROW not found'
    s = s[:m.start()] + block + s[m.end():]
p.write_text(s)
# 2. catalog set:MOD on each role's own line
n = 0
for c in sorted((R / 'catalog').glob('*.catalog.md')):
    t = c.read_text(); out = []
    for line in t.split('\n'):
        m = re.match(r'^- \*\*([a-z0-9-]+)\*\* ', line)
        if m and m.group(1) in borrow:
            sm = re.search(r' · set:([A-Z!,]+) · ', line)
            if sm and 'MOD' not in sm.group(1).replace('!', '').split(','):
                line = line[:sm.end(1)] + ',MOD' + line[sm.end(1):]; n += 1
        out.append(line)
    if '\n'.join(out) != t: c.write_text('\n'.join(out))
print(f'MX_BORROW: {len(borrow)} roles ({sum(len(v) for v in borrow.values())} looks); set:MOD added to {n} catalog lines')
