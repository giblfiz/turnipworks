#!/usr/bin/env python3
"""inventory.json + corpus-results.json (browser_barcat.py --dump) -> inventory.md: everything the bar can offer, and how
findable each one is.  python3 inventory.py [BEFORE_DIR] AFTER_DIR > inventory.md

  well     a corpus line wants it and it is the top row (or nothing in the corpus wants it, and it has words of its own
           beyond its title)
  poorly   found, but only lower in the top 3, or only by its own title (no synonyms and no corpus line)
  not      a corpus line wants it and it is not in the top 3; or it is hidden (keys / typed forms only)
  (state)  not offered in any selection the suite probes (it needs a state the scene does not have: a clipboard, a
           cut, a fight, a template, roofs on …); its words are listed all the same
"""
import collections, fnmatch, json, os, sys

def load(d):
    return json.load(open(os.path.join(d, 'inventory.json'))), json.load(open(os.path.join(d, 'corpus-results.json')))

def grade(inv, res):
    """-> {ref: 'well' | 'poorly' | 'not'} from the corpus lines that want each ref (globs expanded over the inventory)"""
    refs = [f"cmd:{c['id']}" for c in inv['commands']] + [f"cat:{c['id']}" for c in inv['catalog']] + [f"fig:{f['id']}" for f in inv['figures']]
    by = collections.defaultdict(list)
    for c in res['cases']:
        for w in c['want']:
            for r in (fnmatch.filter(refs, w) if '*' in w else [w]): by[r].append(c['pos'])
    out = {}
    for r, ps in by.items():
        out[r] = 'well' if any(p == 0 for p in ps) else 'poorly' if any(p is not None and p < 3 for p in ps) else 'not'
    return out

def main():
    dirs = sys.argv[1:]
    after_inv, after_res = load(dirs[-1])
    before = load(dirs[0]) if len(dirs) > 1 else None
    g_after = grade(after_inv, after_res); g_before = grade(*before) if before else {}
    def mark(c, g):
        r = f"cmd:{c['id']}"
        if c['hidden'] and not c['parse']: return 'not'
        if r in g: return g[r]
        return 'well' if len(c['synonyms']) > 0 else 'poorly'
    P = print
    P('# The bar\'s catalog: inventory (2026-10-20)\n')
    P('Generated by `experiments/2026-10-20-bar-catalog/inventory.py` from `browser_barcat.py --dump` (the real bar, a GM and a player seat, a scene with rooms, a whole temple, a pawn, a crate, a door, a lantern, a hidden chest and a second area). Marks: **well** = the top row for a corpus line that wants it (or, with no line, it has words of its own); **poorly** = only lower in the top 3, or only by its own title; **not** = a corpus line wants it and misses the top 3, or hidden (keys and typed forms only); **state** = not offered in any probed selection, so it needs a state the scene lacks.\n')
    if before:
        bi, br = before
        P(f"**Corpus:** {after_res['n']} lines. Before (origin/main): hit@1 {br['hit1']}/{br['n']} = {br['hit1']/br['n']:.3f}, hit@3 {br['hit3']}/{br['n']} = {br['hit3']/br['n']:.3f}. After: hit@1 {after_res['hit1']}/{after_res['n']} = {after_res['hit1']/after_res['n']:.3f}, hit@3 {after_res['hit3']}/{after_res['n']} = {after_res['hit3']/after_res['n']:.3f}. Lines missing the top 3: {br['n'] - br['hit3']} → {after_res['n'] - after_res['hit3']}.\n")
        cnt = lambda g, pre: collections.Counter(v for k, v in g.items() if k.startswith(pre))
        for pre, name in [('cmd:', 'commands'), ('cat:', 'catalog things'), ('fig:', 'figures')]:
            P(f"- {name} a corpus line wants: before {dict(cnt(g_before, pre))} · after {dict(cnt(g_after, pre))}")
        P('')
    inv = after_inv
    P(f"**Counts:** {len(inv['commands'])} commands ({sum(c['hidden'] for c in inv['commands'])} hidden, {sum(c['stub'] for c in inv['commands'])} stubs), {len(inv['catalog'])} catalog things ({collections.Counter(c['place'] for c in inv['catalog'])}), {len(inv['figures'])} figures, {len(inv['roomTypes'])} room types, {len(inv['buildingTypes'])} building types ({sum(b['disabled'] for b in inv['buildingTypes'])} not built yet: {', '.join(b['label'] for b in inv['buildingTypes'] if b['disabled'])}).\n")
    P('## Commands\n')
    groups = collections.defaultdict(list)
    for c in inv['commands']: groups[c['group']].append(c)
    for gname, cs in groups.items():
        if len(cs) > 30:  # the long generated families: one line each
            ms = collections.Counter(mark(c, g_after) for c in cs)
            P(f"### {gname} — {len(cs)} commands, generated (one per type / material): {dict(ms)}\n")
            P('Examples: ' + '; '.join(f"`{c['id']}` {c['title']}" for c in cs[:4]) + '\n')
            continue
        P(f"### {gname}\n\n| id | title | words | keys | seen by | where | mark |\n|---|---|---|---|---|---|---|")
        for c in cs:
            m = mark(c, g_after); was = mark(c, g_before) if before and f"cmd:{c['id']}" in g_before else None
            pl = 'player' if c['id'] in set(inv['player']['none']) | set(inv['player']['pawn']) else 'GM'
            st = '' if c['where'] else ' (state)'
            P(f"| `{c['id']}` | {c['title'][:60]}{' *(hidden)*' if c['hidden'] else ''}{' *(stub)*' if c['stub'] else ''} | {', '.join(c['synonyms'])[:120]} | {' '.join(c['keys'])} | {pl} | {', '.join(c['where']) or '—'} | {m}{st}{'' if not was or was == m else f' (was {was})'} |")
        P('')
    P('## Room types and buildings\n')
    P(', '.join(f"{t['label']} (`{t['key']}`)" for t in inv['roomTypes']) + '\n')
    P(', '.join(f"{b['label']}{' (not built yet)' if b['disabled'] else ''}" for b in inv['buildingTypes']) + '\n')
    P('## Things to place\n')
    pl = collections.defaultdict(list)
    for c in inv['catalog']: pl[c['place']].append(c)
    for k, cs in pl.items():
        graded = [(c, g_after.get(f"cat:{c['id']}")) for c in cs]
        P(f"- **{k}** ({len(cs)}): corpus-graded {dict(collections.Counter(m for _, m in graded if m))}; with extra words: {', '.join(c['id'] + ' (' + ', '.join(c['terms']) + ')' for c in cs if c.get('terms'))[:900] or 'none'}")
    P('\n## Figures\n')
    P(f"{len(inv['figures'])} figures: {dict(collections.Counter(f['group'] for f in inv['figures']))}. Searched by name, class, race, tags and SRD names (figures.js); corpus-graded {dict(collections.Counter(v for k, v in g_after.items() if k.startswith('fig:')))}.\n")
    P('## Corpus lines still missing the top 3\n')
    for c in after_res['cases']:
        if c['pos'] is None or c['pos'] >= c.get('k', 3): P(f"- `{c['q']}` ({c['seat']}, {c['ctx']}) wants {c['want']}, got {c['top'][:3]}")
    if before:
        P('\n## Lines that missed before (origin/main)\n')
        P(', '.join(f"`{c['q']}`{'' if c['ctx'] == 'none' else ' (' + c['ctx'] + ')'}" for c in br['cases'] if c['pos'] is None or c['pos'] >= c.get('k', 3)))

main()
