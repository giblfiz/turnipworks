        if not manifest.exists():
            continue
        for row in load_manifest(manifest):
            glb = CCM / folder / "models" / f"{row['source']}.glb"
            if not glb.exists():
                continue
            if row["sku"] in skus:
                ccm_skipped.append(f"{src}/{row['sku']} (kept {skus[row['sku']]['src']})")
                continue
