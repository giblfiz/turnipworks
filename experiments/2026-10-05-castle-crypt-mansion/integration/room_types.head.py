# ------------------------------------------------------------------------------------------------------------------
# 3. after the objects loop: object-level facts the solver reads
#    hung: the spec said it hangs on the wall (solver.js isHung reads o.hung beside HUNG_IDS)
#    only: every mesh of this role has an exclusive tier -> the role exists only for room types that list that tier
OBJECT_HUNK = '''\
    EXCLUSIVE = {"crypt", "castle", "noble", "storey", "ccm"}  # sku tiers rolled only by room types that list them in `tiers` (the batch block above)
    for obj in objects.values():
        tiers = {s["tier"] for s in obj["skus"]}
        if tiers and tiers <= EXCLUSIVE:
            obj["only"] = sorted(tiers)
        if any(skus[s["sku"]].get("hung") for s in obj["skus"]):
            obj["hung"] = True
        for s in obj["skus"]:
            if skus[s["sku"]].get("fit"):
                s["fit"] = skus[s["sku"]]["fit"]
    visible = lambda oid, rt: not objects[oid].get("only") or any(t in objects[oid]["only"] for t in rt.get("tiers", []))
'''

