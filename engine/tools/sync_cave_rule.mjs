// THE CAVE RULE, ONE SOURCE (2026-10-25). The caves pilot owns the placement rule and the piece measurements
// (experiments/2026-10-05-caves: viewer/cave.js, kit.json, viewer/scenes.js POOL). The game runs the SAME rule: this
// copies it into the engine, byte for byte, and writes the measurements and the piece pool as a module the browser and
// the relay can import. Run it after any change to the pilot's rule:
//     node engine/tools/sync_cave_rule.mjs          (from anywhere; --check: exit 1 if the copies are stale)
// engine/test/caves.test.mjs fails while the copies differ from the pilot, so a stale copy cannot land unnoticed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const PILOT = path.join(ROOT, 'experiments/2026-10-05-caves');
export const RULE_SRC = path.join(PILOT, 'viewer/cave.js'), RULE_DST = path.join(ROOT, 'engine/core/caverule.js');
export const KIT_DST = path.join(ROOT, 'engine/core/cavekit.js');
export async function kitModule() {
  const kit = JSON.parse(fs.readFileSync(path.join(PILOT, 'kit.json'), 'utf8'));
  const { POOL } = await import(pathToFileURL(path.join(PILOT, 'viewer/scenes.js')).href);
  return `// GENERATED by engine/tools/sync_cave_rule.mjs from experiments/2026-10-05-caves/kit.json and viewer/scenes.js (POOL).\n// Do not edit: change the pilot and run the sync. The measured cave pieces (feet, canonical frame: origin on the\n// ground at the middle of the back plane, front +Z) and the pool the rule picks from.\nexport const KIT = ${JSON.stringify(kit)};\nexport const POOL = ${JSON.stringify(POOL)};\n`;
}
export const ruleText = () => fs.readFileSync(RULE_SRC, 'utf8');
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const rule = ruleText(), kit = await kitModule();
  const stale = (f, want) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== want;
  if (process.argv.includes('--check')) {
    const s = [[RULE_DST, rule], [KIT_DST, kit]].filter(([f, w]) => stale(f, w)).map(([f]) => path.relative(ROOT, f));
    if (s.length) { console.log('stale:', s.join(', ')); process.exit(1); }
    console.log('cave rule in sync'); process.exit(0);
  }
  fs.writeFileSync(RULE_DST, rule); fs.writeFileSync(KIT_DST, kit);
  console.log('synced', path.relative(ROOT, RULE_DST), path.relative(ROOT, KIT_DST));
}
