// THE CAVE PIECES' FOOTPRINTS (2026-10-25). For each of the game's cave chunks (engine/client/data/caves/<id>.glb, the
// canonical frame: feet, origin on the ground at the middle of the back plane, front +Z), its PROFILE in plan (below)
// from the floor to head height: the part of the rock a pawn standing on the floor could touch. Written to
// engine/core/cavehulls.js, which core/caves.js uses to keep every chunk out of the floor squares exactly (the browser
// test measures the drawn meshes the same way). Re-run after the chunks are rebuilt:
//     node engine/tools/cave_hulls.mjs          (engine/tools/cave_measure.mjs measures many caves on the real vertices)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const MAIN = '<repo>';
const req = createRequire(path.join(MAIN, 'tools/spawn-tuner/prep/package.json'));
const { NodeIO } = await import(pathToFileURL(req.resolve('@gltf-transform/core')).href);
const { ALL_EXTENSIONS } = await import(pathToFileURL(req.resolve('@gltf-transform/extensions')).href);
const { MeshoptDecoder } = await import(pathToFileURL(req.resolve('meshoptimizer')).href);
await MeshoptDecoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
const { KIT } = await import(pathToFileURL(path.join(ROOT, 'engine/core/cavekit.js')).href);

// every vertex of a piece, in the file's own frame (the canonical one), as [x, y, z]
export async function vertsOf(id) {
  const dir = fs.existsSync(path.join(ROOT, 'engine/client/data/caves', `${id}.glb`)) ? path.join(ROOT, 'engine/client/data/caves') : path.join(MAIN, 'engine/client/data/caves');
  const doc = await io.read(path.join(dir, `${id}.glb`)), out = [], e = [0, 0, 0];
  for (const node of doc.getRoot().listNodes()) {
    const mesh = node.getMesh(); if (!mesh) continue; const M = node.getWorldMatrix();
    for (const p of mesh.listPrimitives()) { const P = p.getAttribute('POSITION'); for (let i = 0; i < P.getCount(); i++) { P.getElement(i, e); out.push([M[0] * e[0] + M[4] * e[1] + M[8] * e[2] + M[12], M[1] * e[0] + M[5] * e[1] + M[9] * e[2] + M[13], M[2] * e[0] + M[6] * e[1] + M[10] * e[2] + M[14]]); } }
  }
  return out;
}
// THE PROFILE of a piece: for every BIN ft across its width (x), the nearest and farthest z of its vertices between
// 0.12 and 7 ft up in its own frame (the band a pawn could touch at any height scale the rule gives a piece: a wall is
// drawn 1.0 to 1.15 times its height, rubble 0.8 to 1.15 times). An x-monotone outline in plan, much tighter than a hull.
export const BIN = 0.2, BAND = [0.12, 7.0];
export function profileOf(v) {
  const bins = new Map();
  for (const [x, y, z] of v) { if (y < BAND[0] || y > BAND[1]) continue; const b = Math.round(x / BIN), r = bins.get(b); if (!r) bins.set(b, [z, z]); else { if (z < r[0]) r[0] = z; if (z > r[1]) r[1] = z; } }
  return [...bins.entries()].sort((a, b) => a[0] - b[0]).map(([b, [lo, hi]]) => [+(b * BIN).toFixed(2), +lo.toFixed(3), +hi.toFixed(3)]);
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const ids = Object.keys(KIT).filter(k => !k.startsWith('_')), prof = {};
  for (const id of ids) { prof[id] = profileOf(await vertsOf(id)); console.log(id, 'bins', prof[id].length); }
  fs.writeFileSync(path.join(ROOT, 'engine/core/cavehulls.js'), `// GENERATED by engine/tools/cave_hulls.mjs from engine/client/data/caves/*.glb. Each cave piece's footprint in plan,\n// from the floor to head height: [x, nearest z, farthest z] every ${BIN} ft across its width (feet, canonical frame:\n// origin on the ground at the middle of the back plane, front +Z). core/caves.js keeps every chunk out of the floor\n// squares with it (the pilot's rule places a few by its measured reach alone, which a turn can beat).\nexport const PROFILE_BIN = ${BIN};\nexport const PROFILES = ${JSON.stringify(prof)};\n`);
  console.log('wrote engine/core/cavehulls.js');
}
